/// Writes the PostgreSQL form of every reference migration the package ships.
///
/// The reference migrations under `example/<module>/migrations/` are written in
/// the framework's canonical DDL — MariaDB's spelling — in two trees: the
/// system tree `system/<datasource>/<schema>/`, applied once to the system
/// schema, and the tenant tree `tenant/<type>/<datasource>/`, applied where each
/// tenant's data lives. Each file is translated with
/// `PostgresSqlDialect.translateCanonicalScript` into
/// `example/<module>/migrations_postgresql/` at the same relative path, so a
/// PostgreSQL deployment copies that tree the way a MariaDB one copies the
/// other.
///
/// The PostgreSQL files are generated, never edited: change the canonical file
/// and run this again. `test/postgres_migrations_test.dart` fails while the two
/// disagree.
///
///     dart run tool/generate_postgres_migrations.dart
library;

import 'dart:io';

import 'package:path/path.dart' as p;
import 'package:tom_core_server/tom_core_server.dart';

/// The two trees inside a module's `migrations/` directory.
const List<String> migrationTrees = ['system', 'tenant'];

/// The header a generated file opens with, naming the file it came from by its
/// path under `migrations/` ([canonicalPath], `/`-separated).
String generatedHeader(String canonicalPath) =>
    '-- PostgreSQL form of migrations/$canonicalPath,\n'
    '-- generated by tool/generate_postgres_migrations.dart. Do not edit: change\n'
    '-- that file and run the tool again.\n';

/// The PostgreSQL file for the canonical [script] at [canonicalPath] under
/// `migrations/`.
String postgresMigration(String canonicalPath, String script) =>
    '${generatedHeader(canonicalPath)}\n'
    '${PostgresSqlDialect().translateCanonicalScript(script)}\n';

/// [canonical]'s path under its module's `migrations/` directory,
/// `/`-separated.
String canonicalPathOf(File canonical) {
  final parts = p.split(canonical.path);
  return p.posix.joinAll(parts.sublist(parts.lastIndexOf('migrations') + 1));
}

/// Every canonical reference migration, by module and tree, with its
/// PostgreSQL path.
Iterable<(File canonical, File postgres)> referenceMigrations(
  Directory root,
) sync* {
  final example = Directory(p.join(root.path, 'example'));
  final modules = example.listSync().whereType<Directory>().toList()
    ..sort((a, b) => a.path.compareTo(b.path));
  for (final module in modules) {
    for (final tree in migrationTrees) {
      final directory = Directory(p.join(module.path, 'migrations', tree));
      if (!directory.existsSync()) continue;
      final files =
          directory
              .listSync(recursive: true)
              .whereType<File>()
              .where((f) => f.path.endsWith('.sql'))
              .toList()
            ..sort((a, b) => a.path.compareTo(b.path));
      for (final file in files) {
        yield (
          file,
          File(
            p.join(
              module.path,
              'migrations_postgresql',
              p.relative(file.path, from: p.join(module.path, 'migrations')),
            ),
          ),
        );
      }
    }
  }
}

void main() {
  for (final (canonical, postgres) in referenceMigrations(Directory.current)) {
    postgres.parent.createSync(recursive: true);
    postgres.writeAsStringSync(
      postgresMigration(
        canonicalPathOf(canonical),
        canonical.readAsStringSync(),
      ),
    );
    stdout.writeln(p.relative(postgres.path));
  }
}
