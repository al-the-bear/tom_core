/// Writes the PostgreSQL form of every reference migration the package ships.
///
/// The reference migrations under `example/<module>/migrations/main/tomcore/`
/// are written in the framework's canonical DDL — MariaDB's spelling. Each is
/// translated with `PostgresSqlDialect.translateCanonicalScript` into
/// `example/<module>/migrations_postgresql/main/tomcore/`, under the same file
/// name, so a PostgreSQL deployment copies that tree the way a MariaDB one
/// copies the other.
///
/// The PostgreSQL files are generated, never edited: change the canonical file
/// and run this again. `test/postgres_migrations_test.dart` fails while the two
/// disagree.
///
///     dart run tool/generate_postgres_migrations.dart
library;

import 'dart:io';

import 'package:path/path.dart' as p;
import 'package:tom_core_server/tom_core_server.dart';

/// The chain directory inside a module's migration tree.
const String chainDirectory = 'main/tomcore';

/// The header a generated file opens with, naming the file it came from.
String generatedHeader(String canonicalFile) =>
    '-- PostgreSQL form of ../../../migrations/$chainDirectory/$canonicalFile,\n'
    '-- generated by tool/generate_postgres_migrations.dart. Do not edit: change\n'
    '-- that file and run the tool again.\n';

/// The PostgreSQL file for the canonical [script] named [canonicalFile].
String postgresMigration(String canonicalFile, String script) =>
    '${generatedHeader(canonicalFile)}\n'
    '${PostgresSqlDialect().translateCanonicalScript(script)}\n';

/// Every canonical reference migration, by module, with its PostgreSQL path.
Iterable<(File canonical, File postgres)> referenceMigrations(
  Directory root,
) sync* {
  final example = Directory(p.join(root.path, 'example'));
  for (final module in example.listSync().whereType<Directory>()) {
    final chain = Directory(p.join(module.path, 'migrations', chainDirectory));
    if (!chain.existsSync()) continue;
    final files =
        chain
            .listSync()
            .whereType<File>()
            .where((f) => f.path.endsWith('.sql'))
            .toList()
          ..sort((a, b) => a.path.compareTo(b.path));
    for (final file in files) {
      yield (
        file,
        File(
          p.join(
            module.path,
            'migrations_postgresql',
            chainDirectory,
            p.basename(file.path),
          ),
        ),
      );
    }
  }
}

void main() {
  for (final (canonical, postgres) in referenceMigrations(Directory.current)) {
    postgres.parent.createSync(recursive: true);
    postgres.writeAsStringSync(
      postgresMigration(
        p.basename(canonical.path),
        canonical.readAsStringSync(),
      ),
    );
    stdout.writeln(p.relative(postgres.path));
  }
}
