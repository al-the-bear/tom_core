/// The PostgreSQL dialect and the driver's placeholder rewrite, without a
/// server: how the framework's canonical DDL and statements read on
/// PostgreSQL.
library;

import 'package:test/test.dart';
import 'package:tom_core_server/tom_core_server.dart';

void main() {
  final dialect = PostgresSqlDialect();

  group('column types', () {
    test('the canonical vocabulary in PostgreSQL\'s words', () {
      for (final (canonical, stored) in const [
        ('DATETIME(6)', 'TIMESTAMP(6)'),
        ('DATETIME', 'TIMESTAMP'),
        ('TINYINT(1)', 'SMALLINT'),
        ('INT', 'INTEGER'),
        ('MEDIUMINT', 'INTEGER'),
        ('BIGINT', 'BIGINT'),
        ('DOUBLE', 'DOUBLE PRECISION'),
        ('LONGTEXT', 'TEXT'),
        ('CHAR(64)', 'VARCHAR(64)'),
        ('VARCHAR(191)', 'VARCHAR(191)'),
        ('LONGBLOB', 'BYTEA'),
        ('DECIMAL(10,2)', 'DECIMAL(10,2)'),
        ('DATE', 'DATE'),
      ]) {
        expect(dialect.columnType(canonical), stored, reason: canonical);
      }
    });

    test('a PostgreSQL type name classifies into its family', () {
      expect(dialect.typeFamily('BYTEA'), TomSqlTypeFamily.binary);
      expect(dialect.typeFamily('TIMESTAMP(6)'), TomSqlTypeFamily.dateTime);
      expect(dialect.typeFamily('BIGSERIAL'), TomSqlTypeFamily.integer);
      expect(dialect.typeFamily('DOUBLE PRECISION'), TomSqlTypeFamily.decimal);
    });
  });

  group('a framework table', () {
    final table = TomFrameworkTable(
      kind: TomTableKind.system,
      name: 'thing',
      origin: 'test',
      columns: const [
        TomFrameworkColumn('id', 'BIGINT', autoIncrement: true),
        TomFrameworkColumn('name', 'VARCHAR(64)'),
        TomFrameworkColumn('done', 'TINYINT(1)', defaultValue: '0'),
        TomFrameworkColumn('at', 'DATETIME(6)', nullable: true),
      ],
      primaryKey: const ['id'],
      keys: const [
        TomFrameworkKey.unique('name', ['name']),
        TomFrameworkKey('at', ['at']),
      ],
    );

    test('is created with an identity, a constraint and a separate index', () {
      final statements = table.createStatements(dialect);
      expect(statements, hasLength(2));
      expect(
        statements.first,
        allOf(
          startsWith('CREATE TABLE IF NOT EXISTS thing ('),
          contains(
            'id   BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY',
          ),
          contains('done SMALLINT     NOT NULL DEFAULT 0'),
          contains('at   TIMESTAMP(6) NULL'),
          contains('CONSTRAINT uq_thing_name UNIQUE (name)'),
          isNot(contains('KEY ix_thing_at')),
        ),
      );
      expect(
        statements.last,
        'CREATE INDEX IF NOT EXISTS ix_thing_at ON thing (at)',
      );
    });

    test('keeps its canonical rendering for the convergence guard', () {
      expect(
        table.createTableDdl,
        allOf(
          contains('AUTO_INCREMENT'),
          contains('KEY ix_thing_at (at)'),
          contains('DATETIME(6)'),
        ),
      );
    });
  });

  group('translateCanonical', () {
    test('rewrites a hand-written CREATE TABLE', () {
      final statements = dialect.translateCanonical('''
CREATE TABLE IF NOT EXISTS `tom_grant` (
  id        BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  owner     VARCHAR(191) COLLATE utf8mb4_bin NOT NULL COMMENT 'who',
  active    TINYINT(1)   NOT NULL DEFAULT TRUE,
  stored_at DATETIME(6)  NOT NULL ON UPDATE CURRENT_TIMESTAMP(6),
  check_at  DATETIME(6)  NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_owner (owner),
  KEY idx_stored (stored_at, owner(32))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;''');
      expect(statements, [
        'CREATE TABLE IF NOT EXISTS tom_grant (\n'
            '  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n'
            '  owner VARCHAR(191) COLLATE "C" NOT NULL,\n'
            '  active SMALLINT NOT NULL DEFAULT 1,\n'
            '  stored_at TIMESTAMP(6) NOT NULL,\n'
            '  check_at TIMESTAMP(6) NULL,\n'
            '  PRIMARY KEY (id),\n'
            '  CONSTRAINT tom_grant_uq_owner UNIQUE (owner)\n'
            ')',
        'CREATE INDEX IF NOT EXISTS tom_grant_idx_stored ON tom_grant '
            '(stored_at, owner)',
      ]);
    });

    test('rewrites an added column and resets identities on truncate', () {
      expect(
        dialect.translateCanonical(
          'ALTER TABLE t ADD COLUMN flag TINYINT(1) NULL',
        ),
        ['ALTER TABLE t ADD COLUMN flag SMALLINT NULL'],
      );
      expect(
        dialect.translateCanonical(
          "CREATE TABLE t (grade ENUM('none','read') NOT NULL DEFAULT 'none')",
        ),
        [
          'CREATE TABLE t (\n'
              "  grade VARCHAR(255) NOT NULL DEFAULT 'none' "
              "CHECK (grade IN ('none', 'read'))\n"
              ')',
        ],
      );
      expect(
        dialect.translateCanonical(
          'ALTER TABLE t MODIFY COLUMN c VARCHAR(32) NOT NULL',
        ),
        [
          'ALTER TABLE t ALTER COLUMN c TYPE VARCHAR(32) USING c::VARCHAR(32), '
              'ALTER COLUMN c SET NOT NULL',
        ],
      );
      expect(dialect.translateCanonical('TRUNCATE TABLE t'), [
        'TRUNCATE TABLE t RESTART IDENTITY',
      ]);
    });

    test('keeps a leading comment header and renders a refusing trigger', () {
      final statements = dialect.translateCanonical(
        '-- header\n'
        "CREATE TRIGGER IF NOT EXISTS trg_t_no_update BEFORE UPDATE ON t "
        "FOR EACH ROW SIGNAL SQLSTATE '45000' "
        "SET MESSAGE_TEXT = 'no updates'",
      );
      expect(statements, hasLength(2));
      expect(
        statements.first,
        allOf(
          startsWith(
            '-- header\nCREATE OR REPLACE FUNCTION trg_t_no_update_reject()',
          ),
          contains("RAISE EXCEPTION ''no updates''"),
        ),
      );
      expect(
        statements.last,
        'CREATE OR REPLACE TRIGGER trg_t_no_update BEFORE UPDATE ON t '
        'FOR EACH ROW EXECUTE FUNCTION trg_t_no_update_reject()',
      );
    });

    test('runs anything else as written, minus backticks', () {
      expect(dialect.translateCanonical('DROP TABLE IF EXISTS `t`;'), [
        'DROP TABLE IF EXISTS t',
      ]);
    });

    test('is the identity on the standard dialect', () {
      const ddl = 'CREATE TABLE t (id BIGINT NOT NULL AUTO_INCREMENT)';
      expect(MariadbSqlDialect().translateCanonical(ddl), [ddl]);
    });
  });

  group('upsert', () {
    final values = {'a': ':a', 'b': ':b', 'c': ':c'};

    test('PostgreSQL names the conflict key and returns the row key', () {
      expect(
        dialect.upsert(
          't',
          values,
          conflictKey: const ['a'],
          updateColumns: const ['b', 'c'],
          keyColumn: 'id',
        ),
        'INSERT INTO t (a, b, c) VALUES (:a, :b, :c) ON CONFLICT (a) '
        'DO UPDATE SET b = EXCLUDED.b, c = EXCLUDED.c RETURNING id',
      );
      expect(
        dialect.upsert(
          't',
          values,
          conflictKey: const ['a', 'b', 'c'],
          updateColumns: const [],
        ),
        'INSERT INTO t (a, b, c) VALUES (:a, :b, :c) '
        'ON CONFLICT (a, b, c) DO NOTHING',
      );
    });

    test('MariaDB updates on the duplicate key and reports the row key', () {
      expect(
        MariadbSqlDialect().upsert(
          't',
          values,
          conflictKey: const ['a'],
          updateColumns: const ['b', 'c'],
          keyColumn: 'id',
        ),
        'INSERT INTO t (a, b, c) VALUES (:a, :b, :c) ON DUPLICATE KEY UPDATE '
        'b = VALUES(b), c = VALUES(c), id = LAST_INSERT_ID(id)',
      );
      expect(
        MariadbSqlDialect().upsert(
          't',
          values,
          conflictKey: const ['a', 'b', 'c'],
          updateColumns: const [],
        ),
        'INSERT INTO t (a, b, c) VALUES (:a, :b, :c) '
        'ON DUPLICATE KEY UPDATE a = a',
        reason: 'nothing to overwrite keeps the row as it is',
      );
    });
  });

  group('literals and predicates', () {
    test('a backslash in a string literal is kept single', () {
      expect(dialect.text(r"it's a \ path"), r"'it''s a \ path'");
    });

    test('a truth value is 1 or 0, matching the SMALLINT it compares with', () {
      expect(dialect.boolOp(true), '1');
      expect(dialect.boolOp(false), '0');
    });

    test('a generated key is asked for with RETURNING', () {
      expect(
        dialect.returningKey('INSERT INTO t (a) VALUES (:a)', 'id'),
        'INSERT INTO t (a) VALUES (:a) RETURNING id',
      );
      expect(
        MariadbSqlDialect().returningKey('INSERT INTO t (a) VALUES (:a)', 'id'),
        'INSERT INTO t (a) VALUES (:a)',
      );
    });
  });

  group('the driver\'s placeholder rewrite', () {
    final driver = PostgresDatasource();

    void expectRewrite(String named, String sql, List<String> names) {
      final (rewritten, slots) = driver.toPositional(named);
      expect(rewritten, sql);
      expect(slots, names);
    }

    test('numbers each occurrence, repeats included', () {
      expectRewrite(
        'SELECT * FROM t WHERE a = :a AND b = :b OR a = :a',
        r'SELECT * FROM t WHERE a = $1 AND b = $2 OR a = $3',
        ['a', 'b', 'a'],
      );
    });

    test('leaves a cast alone', () {
      expectRewrite(
        'SELECT :v::text, x::int FROM t',
        r'SELECT $1::text, x::int FROM t',
        ['v'],
      );
    });

    test('reads a backslash in a literal as PostgreSQL does', () {
      // `'\'` is a one-character literal in PostgreSQL; read with MariaDB's
      // escaping it would swallow the closing quote and hide `:x`.
      expectRewrite(
        r"SELECT 1 FROM t WHERE a LIKE :p ESCAPE '\' AND b = :x",
        r"SELECT 1 FROM t WHERE a LIKE $1 ESCAPE '\' AND b = $2",
        ['p', 'x'],
      );
    });
  });

  group('the driver\'s settings', () {
    test('an sslMode that is none of the three is refused by name', () async {
      final driver = PostgresDatasource()
        ..host = '127.0.0.1'
        ..port = 1
        ..sslMode = 'sometimes';
      await expectLater(
        driver.connect(),
        throwsA(
          isA<PostgresDatasourceException>().having(
            (e) => e.key,
            'key',
            'error.initialize.invalid_ssl_mode',
          ),
        ),
      );
    });

    test('defaults to PostgreSQL\'s port and to an encrypted connection', () {
      final driver = PostgresDatasource();
      expect(driver.port, 5432);
      expect(driver.sslMode, 'require');
    });
  });
}
