/// Thrown for PostgreSQL migration failures; see [TomSqlMigrationException].
class PostgresMigrationException extends TomSqlMigrationException {
  /// Creates the exception with a message [key] and [defaultUserMessage]; the
  /// remaining parameters mirror [TomSqlMigrationException].
  PostgresMigrationException(
    super.key,
    super.defaultUserMessage, {
    super.parameters,
    super.stack,
    super.rootException,
    super.autoLog,
  });
}

/// The PostgreSQL [TomDbMigrator] (registered for the `"postgresql"` type);
/// see [TomSqlMigrationAdaptor] for the history, checksum and rebinding rules
/// every SQL adaptor shares.
///
/// **PostgreSQL rolls DDL back, and this adaptor relies on it.** A migration's
/// statements and the row recording it run in one transaction: a script that
/// fails part-way is undone entirely, nothing is recorded, and the next run
/// applies it again from the start. That is the difference from the MariaDB
/// adaptor, which has to record a failed script and refuse the schema until a
/// person repairs it, because MariaDB leaves the statements that ran in place.
///
/// The one kind of statement this cannot cover is one PostgreSQL refuses inside
/// a transaction — `CREATE INDEX CONCURRENTLY`, `CREATE DATABASE`, `VACUUM`.
/// Such a script fails with the server's own message naming the statement; it
/// belongs in a separate, single-statement operation outside the migration
/// chain.
@TomDbMigrationAdaptor("postgresql")
@tomReflector
class PostgresMigrationAdaptor extends TomSqlMigrationAdaptor {
  @override
  String get adaptorLabel => "PostgresMigrationAdaptor";

  @override
  String get applyKeyPrefix => "postgres_migration";

  @override
  String get initializeKeyPrefix => "postgres_migration_adapter";

  @override
  TomServerException migrationException(
    String key,
    String message, {
    Map<String, dynamic>? parameters,
    Object? rootException,
    bool autoLog = false,
  }) => PostgresMigrationException(
    key,
    message,
    parameters: parameters,
    rootException: rootException,
    autoLog: autoLog,
  );

  /// The versioning table, column for column the MariaDB one, in PostgreSQL's
  /// words. The camel-case column names fold to lower case in PostgreSQL, and
  /// read back as the same names because PostgreSQL results are matched
  /// without regard to case.
  @override
  String versioningTableDdl(String schemaName) =>
      '''
CREATE TABLE IF NOT EXISTS ${schemaName}_versioning (
  installedRank INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version INTEGER NOT NULL DEFAULT -1,
  description VARCHAR(500) NOT NULL DEFAULT '',
  script TEXT NOT NULL DEFAULT '',
  checksum VARCHAR(200) NOT NULL DEFAULT '',
  installedBy VARCHAR(63) NOT NULL DEFAULT CURRENT_USER,
  installedOn TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  executionTimeMs INTEGER NOT NULL DEFAULT 0,
  success SMALLINT NOT NULL DEFAULT 0
)''';

  @override
  Future<void> applyScript(
    TomDataSourceInfo dsi,
    String schemaName,
    int version,
    String description,
    String sql,
  ) async {
    try {
      await TomTransactionManager.runInTransaction((_) async {
        final timer = Stopwatch()..start();
        for (final statement in TomSqlLexer.splitStatements(
          sql,
          backslashEscapes: false,
        )) {
          await dsi.datasource.executeCommand(statement);
        }
        await recordMigration(
          dsi,
          schemaName,
          version,
          description,
          sql,
          success: true,
          elapsedMs: (timer..stop()).elapsedMilliseconds,
        );
      });
    } catch (error) {
      throw migrationException(
        "$applyKeyPrefix.apply_migration.failed",
        "Failed to apply migration $version, $description — rolled back, "
            "nothing was applied: $error",
        autoLog: true,
        rootException: error,
      );
    }
  }
}
