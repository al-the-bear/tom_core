import 'sql_dialects.dart';
import 'types_operator.dart';

/// The SQL dialect for PostgreSQL (15 and later).
///
/// Nothing looks it up: `PostgresDatasource.sqlDialect` returns an instance,
/// and everything that renders SQL asks its data source — see
/// `MariadbSqlDialect` for why a dialect arrives with its driver.
///
/// ## The canonical types, in PostgreSQL's words
///
/// The framework declares its tables in one type vocabulary — MariaDB's
/// spelling — and [columnType] translates it:
///
/// | Declared | Stored as | Why |
/// | -------- | --------- | --- |
/// | `DATETIME(n)` | `TIMESTAMP(n)` | both hold a wall reading with no zone; the framework writes UTC into it |
/// | `TINYINT(1)`, `TINYINT` | `SMALLINT` | a truth value is bound as `1`/`0` on every database, so it stays an integer here too |
/// | `MEDIUMINT` | `INTEGER` | |
/// | `DOUBLE` | `DOUBLE PRECISION` | |
/// | `FLOAT` | `REAL` | |
/// | `TINYTEXT`, `MEDIUMTEXT`, `LONGTEXT` | `TEXT` | PostgreSQL's `TEXT` has no size classes |
/// | `CHAR(n)` | `VARCHAR(n)` | PostgreSQL pads a `CHAR(n)` on read; MariaDB strips the padding, and the framework's code expects that |
/// | `BLOB` and its sizes, `VARBINARY(n)`, `BINARY(n)` | `BYTEA` | |
/// | `ENUM(…)` | `VARCHAR(255)` | the values are checked by the code that writes them |
/// | `… AUTO_INCREMENT` | `… GENERATED BY DEFAULT AS IDENTITY` | |
///
/// ## Truth values
///
/// A Dart `bool` is bound as `1`/`0` and a framework truth column is a
/// `SMALLINT`, so a boolean literal renders as `1`/`0` as well ([boolOp]); a
/// `true` compared with a `SMALLINT` is a type error in PostgreSQL.
class PostgresSqlDialect extends TomStandardSqlDialect {
  /// A string literal: single quotes doubled, nothing else.
  ///
  /// PostgreSQL reads a backslash in an ordinary literal as itself
  /// (`standard_conforming_strings`, on since 9.1), so doubling it — as the
  /// MariaDB rendering must — would store two.
  @override
  SqlString text(String text) => "'${text.replaceAll("'", "''")}'";

  /// `1` or `0`; see the class documentation.
  @override
  SqlString boolOp(bool value) => value ? '1' : '0';

  /// PostgreSQL reads a backslash in an ordinary literal as itself.
  @override
  bool get backslashEscapes => false;

  /// `TRUE` or `FALSE`: a predicate has to be a boolean.
  @override
  SqlString truthPredicate(bool value) => value ? 'TRUE' : 'FALSE';

  /// `<text> ~ <test>`, PostgreSQL's POSIX regular-expression match.
  @override
  SqlString regexp(
    TomOperator<TomDbString> text,
    TomOperator<TomDbString> test,
  ) => "${text.generate(this)} ~ ${test.generate(this)}";

  /// The standard families plus PostgreSQL's own type names.
  @override
  TomSqlTypeFamily typeFamily(String sqlType) {
    return switch (baseTypeName(sqlType)) {
      'BIGSERIAL' ||
      'SMALLSERIAL' ||
      'INT2' ||
      'INT4' ||
      'INT8' => TomSqlTypeFamily.integer,
      'FLOAT4' || 'FLOAT8' => TomSqlTypeFamily.decimal,
      'BYTEA' => TomSqlTypeFamily.binary,
      'TIMESTAMPTZ' => TomSqlTypeFamily.dateTime,
      'TIMETZ' => TomSqlTypeFamily.time,
      'JSONB' || 'CITEXT' || 'BPCHAR' => TomSqlTypeFamily.text,
      _ => super.typeFamily(sqlType),
    };
  }

  @override
  String columnType(String canonicalType) {
    final base = baseTypeName(canonicalType);
    final arguments = typeArguments(canonicalType);
    final suffix = arguments.isEmpty ? '' : '(${arguments.join(', ')})';
    return switch (base) {
      'DATETIME' => 'TIMESTAMP$suffix',
      'TINYINT' => 'SMALLINT',
      'MEDIUMINT' => 'INTEGER',
      'INT' => 'INTEGER',
      'DOUBLE' => 'DOUBLE PRECISION',
      'FLOAT' => 'REAL',
      'TINYTEXT' || 'MEDIUMTEXT' || 'LONGTEXT' => 'TEXT',
      'CHAR' => 'VARCHAR$suffix',
      'TINYBLOB' ||
      'BLOB' ||
      'MEDIUMBLOB' ||
      'LONGBLOB' ||
      'VARBINARY' ||
      'BINARY' => 'BYTEA',
      'ENUM' => 'VARCHAR(255)',
      _ => canonicalType,
    };
  }

  @override
  SqlString columnDefinition({
    required String name,
    required String type,
    required bool nullable,
    String? defaultValue,
    bool autoIncrement = false,
    int nameWidth = 0,
    int typeWidth = 0,
  }) {
    final buffer = StringBuffer()
      ..write(name.padRight(nameWidth))
      ..write(' ')
      ..write(columnType(type).padRight(typeWidth))
      ..write(' ')
      ..write(nullable ? 'NULL' : 'NOT NULL');
    if (defaultValue != null) buffer.write(' DEFAULT $defaultValue');
    if (autoIncrement) buffer.write(' GENERATED BY DEFAULT AS IDENTITY');
    return buffer.toString();
  }

  /// PostgreSQL declares no index inside `CREATE TABLE`; only uniqueness.
  @override
  bool get declaresIndexesInline => false;

  @override
  SqlString keyDefinition(
    String name,
    List<String> columns, {
    required bool unique,
  }) => 'CONSTRAINT $name UNIQUE (${columns.join(', ')})';

  /// `INSERT … ON CONFLICT DO NOTHING` for an ignored conflict.
  @override
  SqlString insertInto(
    String table,
    Map<String, String> values, {
    bool ignoreConflict = false,
  }) =>
      'INSERT INTO $table (${values.keys.join(', ')}) '
      'VALUES (${values.values.join(', ')})'
      '${ignoreConflict ? ' ON CONFLICT DO NOTHING' : ''}';

  /// MariaDB's `REPLACE`, as two statements: a `DELETE` of every row the new
  /// one supersedes — the one with its primary key, and any colliding on one
  /// of [uniqueKeys] — then the `INSERT`, which keeps
  /// `ON CONFLICT (<key>) DO UPDATE` for a writer that inserted the same key
  /// between the two.
  ///
  /// The other unique keys matter: the job queue's window key is how a second
  /// run for the same window supersedes the first, and an upsert on the primary
  /// key alone would refuse it as a duplicate instead. A key is used only when
  /// the write supplies every one of its columns — a key over a generated
  /// column (the queue's `seq`) cannot collide with a row the write has not
  /// given it. Two statements because one cannot do it: a row deleted by a
  /// `WITH` still holds its key against the `INSERT` of the same statement.
  @override
  List<SqlString> replaceInto(
    String table,
    Map<String, String> values, {
    required List<String> primaryKey,
    List<List<String>> uniqueKeys = const [],
  }) {
    final keyed = {for (final c in values.keys) c.toLowerCase(): values[c]!};
    final superseded = [
      for (final key in [primaryKey, ...uniqueKeys])
        if (key.isNotEmpty &&
            key.every((c) => keyed.containsKey(c.toLowerCase())))
          '(${key.map((c) => '$c = ${keyed[c.toLowerCase()]}').join(' AND ')})',
    ];
    final inPrimaryKey = primaryKey.map((c) => c.toLowerCase()).toSet();
    final updates = [
      for (final column in values.keys)
        if (!inPrimaryKey.contains(column.toLowerCase()))
          '$column = EXCLUDED.$column',
    ];
    final insert =
        'INSERT INTO $table (${values.keys.join(', ')}) '
        'VALUES (${values.values.join(', ')}) '
        'ON CONFLICT (${primaryKey.join(', ')}) '
        '${updates.isEmpty ? 'DO NOTHING' : 'DO UPDATE SET ${updates.join(', ')}'}';
    return [
      if (superseded.isNotEmpty)
        'DELETE FROM $table WHERE ${superseded.join(' OR ')}',
      insert,
    ];
  }

  /// `INSERT … ON CONFLICT (<key>) DO UPDATE SET <column> = EXCLUDED.<column>`,
  /// with `RETURNING <key column>` when one is asked for.
  @override
  SqlString upsert(
    String table,
    Map<String, String> values, {
    required List<String> conflictKey,
    required List<String> updateColumns,
    String? keyColumn,
  }) {
    final update = updateColumns.isEmpty
        ? 'DO NOTHING'
        : 'DO UPDATE SET '
              '${updateColumns.map((c) => '$c = EXCLUDED.$c').join(', ')}';
    return 'INSERT INTO $table (${values.keys.join(', ')}) '
        'VALUES (${values.values.join(', ')}) '
        'ON CONFLICT (${conflictKey.join(', ')}) $update'
        '${keyColumn == null ? '' : ' RETURNING $keyColumn'}';
  }

  @override
  SqlString incrementCounter(
    String table,
    Map<String, String> values,
    String counter, {
    required List<String> conflictKey,
  }) =>
      'INSERT INTO $table (${[...values.keys, counter].join(', ')}) '
      'VALUES (${[...values.values, '1'].join(', ')}) '
      'ON CONFLICT (${conflictKey.join(', ')}) '
      'DO UPDATE SET $counter = $table.$counter + 1 RETURNING $counter';

  @override
  SqlString returningKey(String insert, String keyColumn) =>
      '$insert RETURNING $keyColumn';

  /// `CREATE SCHEMA` — a PostgreSQL schema lives inside the one database.
  @override
  SqlString createSchema(String name) =>
      'CREATE SCHEMA IF NOT EXISTS ${quoteIdentifier(name)}';

  /// The driver's `schema` setting, which sets the session's `search_path`.
  @override
  String get schemaSetting => 'schema';

  @override
  SqlString get currentSchema => 'current_schema()';

  /// The catalogue's answer in MariaDB's column shape: `format_type` for the
  /// type with its length (`character varying(191)`, `timestamp(6) without
  /// time zone`), and `PRI` for a column of the primary key.
  @override
  SqlString get tableColumnsQuery =>
      'SELECT c.column_name AS column_name, '
      'format_type(a.atttypid, a.atttypmod) AS column_type, '
      'c.is_nullable AS is_nullable, '
      "CASE WHEN EXISTS (SELECT 1 FROM pg_index i "
      'WHERE i.indrelid = a.attrelid AND i.indisprimary '
      "AND a.attnum = ANY (i.indkey)) THEN 'PRI' ELSE '' END AS column_key "
      'FROM information_schema.columns c '
      'JOIN pg_attribute a ON a.attrelid = '
      "(quote_ident(c.table_schema) || '.' || quote_ident(c.table_name))::regclass "
      'AND a.attname = c.column_name '
      'WHERE c.table_schema = current_schema() AND c.table_name = :table '
      'ORDER BY c.ordinal_position';

  /// A trigger function raising [message], and the trigger calling it.
  ///
  /// The function body is an ordinary single-quoted literal rather than
  /// dollar-quoted, so the statement splitter sees one statement in it.
  @override
  List<SqlString> rejectingTrigger({
    required String name,
    required String table,
    required String event,
    required String message,
  }) {
    final function = '${name}_reject';
    final quoted = message.replaceAll("'", "''''");
    return [
      'CREATE OR REPLACE FUNCTION $function() RETURNS trigger '
          "LANGUAGE plpgsql AS 'BEGIN RAISE EXCEPTION ''$quoted''; END'",
      'CREATE OR REPLACE TRIGGER $name BEFORE $event ON $table '
          'FOR EACH ROW EXECUTE FUNCTION $function()',
    ];
  }

  @override
  SqlString quoteIdentifier(String identifier) =>
      '"${identifier.replaceAll('"', '""')}"';

  /// The canonical [statement] in PostgreSQL's words.
  ///
  /// * `CREATE TABLE`: each column's type through [columnType],
  ///   `AUTO_INCREMENT` as an identity, `UNSIGNED`, `COMMENT`, `CHARACTER SET`,
  ///   `COLLATE` and `ON UPDATE CURRENT_TIMESTAMP` dropped — except a binary
  ///   collation (`utf8mb4_bin`), which becomes `COLLATE "C"`: both mean
  ///   case-sensitive identity and code-unit order — a `TRUE`/`FALSE`
  ///   default on a truth column as `1`/`0`, inline `UNIQUE KEY`s as
  ///   constraints, inline `KEY`/`INDEX`es as `CREATE INDEX IF NOT EXISTS`
  ///   statements after the table, and the table options (`ENGINE=…`,
  ///   `DEFAULT CHARSET=…`) dropped. An index name is schema-wide in
  ///   PostgreSQL, so one that does not already name its table is prefixed
  ///   with it.
  /// * `ALTER TABLE … ADD [COLUMN] …`: the column translated the same way.
  /// * `ALTER TABLE … MODIFY [COLUMN] …`: PostgreSQL's two actions, a type
  ///   change (converting the stored values with `USING`) and the nullability.
  /// * MariaDB's refusing `CREATE TRIGGER … SIGNAL SQLSTATE` guard: the
  ///   function and trigger [rejectingTrigger] renders.
  /// * `TRUNCATE TABLE …`: `RESTART IDENTITY`, so the identity restarts as an
  ///   `AUTO_INCREMENT` does.
  ///
  /// Backtick quoting is removed throughout; the name then folds to lower case
  /// exactly as every unquoted reference to it does. Leading comment lines are
  /// kept on the first statement. Anything else runs as written.
  @override
  List<SqlString> translateCanonical(String statement) {
    // Leading comment lines — a migration's header — are set aside, the
    // statement translated, and the comments put back on the first statement
    // it became.
    final lines = statement.trim().split('\n');
    var body = 0;
    while (body < lines.length &&
        (lines[body].trim().isEmpty ||
            lines[body].trimLeft().startsWith('--'))) {
      body++;
    }
    final comments = lines.sublist(0, body).join('\n').trimRight();
    final translated = _translateStatement(lines.sublist(body).join('\n'));
    if (comments.isEmpty || translated.isEmpty) return translated;
    return ['$comments\n${translated.first}', ...translated.skip(1)];
  }

  List<SqlString> _translateStatement(String statement) {
    final sql = _unbacktick(
      statement.trim().replaceFirst(RegExp(r';\s*$'), ''),
    );
    if (sql.isEmpty) return const [];
    final trigger = _signalTrigger.firstMatch(sql);
    if (trigger != null) {
      return rejectingTrigger(
        name: trigger.group(1)!,
        event: trigger.group(2)!.toUpperCase(),
        table: trigger.group(3)!,
        message: trigger.group(4)!.replaceAll("''", "'"),
      );
    }
    final create = _createTable.firstMatch(sql);
    if (create != null) return _translateCreate(sql, create);
    final add = _alterAdd.firstMatch(sql);
    if (add != null) {
      return [
        '${add.group(1)}${_columnLine(sql.substring(add.end).trim()).$1}',
      ];
    }
    final modify = _alterModify.firstMatch(sql);
    if (modify != null) {
      final (line, _) = _columnLine(sql.substring(modify.end).trim());
      final column = RegExp(r'^\S+').firstMatch(line)![0]!;
      final type = columnType(
        RegExp(
          r'^\S+\s+(\w+(?:\s*\([^)]*\))?(?:\s+PRECISION)?)',
          caseSensitive: false,
        ).firstMatch(line)!.group(1)!,
      );
      final nullability =
          RegExp(r'\bNOT\s+NULL\b', caseSensitive: false).hasMatch(line)
          ? 'SET NOT NULL'
          : 'DROP NOT NULL';
      return [
        '${modify.group(1)} ALTER COLUMN $column TYPE $type USING '
            '$column::$type, ALTER COLUMN $column $nullability',
      ];
    }
    final truncate = _truncate.firstMatch(sql);
    if (truncate != null) {
      return ['TRUNCATE TABLE ${truncate.group(1)} RESTART IDENTITY'];
    }
    return [sql];
  }

  /// MariaDB's always-refusing trigger: `CREATE TRIGGER … BEFORE <event> ON
  /// <table> FOR EACH ROW SIGNAL SQLSTATE '…' SET MESSAGE_TEXT = '<message>'`.
  static final RegExp _signalTrigger = RegExp(
    r"^CREATE\s+TRIGGER\s+(?:IF\s+NOT\s+EXISTS\s+)?(\w+)\s+BEFORE\s+(\w+)\s+ON\s+([\w.]+)\s+FOR\s+EACH\s+ROW\s+SIGNAL\s+SQLSTATE\s+'\w+'\s+SET\s+MESSAGE_TEXT\s*=\s*'((?:[^']|'')*)'\s*$",
    caseSensitive: false,
  );

  static final RegExp _createTable = RegExp(
    r'^CREATE\s+TABLE\s+(IF\s+NOT\s+EXISTS\s+)?([\w.]+)\s*\(',
    caseSensitive: false,
  );

  static final RegExp _alterAdd = RegExp(
    r'^(ALTER\s+TABLE\s+[\w.]+\s+ADD\s+(?:COLUMN\s+)?)',
    caseSensitive: false,
  );

  /// A table-level constraint rather than a column — matched as a keyword, so
  /// a column called `checkin_at` is not taken for a `CHECK`.
  static final RegExp _tableConstraint = RegExp(
    r'^(PRIMARY\s+KEY|FOREIGN\s+KEY|CHECK|CONSTRAINT)\b(?!_)',
    caseSensitive: false,
  );

  static final RegExp _alterModify = RegExp(
    r'^(ALTER\s+TABLE\s+[\w.]+)\s+MODIFY\s+(?:COLUMN\s+)?',
    caseSensitive: false,
  );

  static final RegExp _truncate = RegExp(
    r'^TRUNCATE\s+(?:TABLE\s+)?([\w.]+)$',
    caseSensitive: false,
  );

  List<String> _translateCreate(String sql, RegExpMatch create) {
    final ifNotExists = create.group(1) == null ? '' : 'IF NOT EXISTS ';
    final table = create.group(2)!;
    final open = create.end - 1;
    final close = _matching(sql, open);
    final lines = <String>[];
    final indexes = <String>[];
    for (final item in _splitTopLevel(sql.substring(open + 1, close))) {
      final key = RegExp(
        r'^(UNIQUE\s+(?:KEY|INDEX)|UNIQUE|KEY|INDEX|FULLTEXT\s+(?:KEY|INDEX))\s+(\w+)?\s*\((.*)\)\s*$',
        caseSensitive: false,
      ).firstMatch(item);
      if (_tableConstraint.hasMatch(item)) {
        lines.add(item);
      } else if (key != null) {
        final kind = key.group(1)!.toUpperCase();
        final columns = _keyColumns(key.group(3)!);
        final name = _indexName(table, key.group(2) ?? columns.join('_'));
        if (kind.startsWith('UNIQUE')) {
          lines.add(keyDefinition(name, columns, unique: true));
        } else {
          indexes.add(createIndex(name, table, columns));
        }
      } else {
        final (line, _) = _columnLine(item);
        lines.add(line);
      }
    }
    return [
      'CREATE TABLE $ifNotExists$table (\n'
          '${lines.map((l) => '  $l').join(',\n')}\n'
          ')',
      ...indexes,
    ];
  }

  /// One column definition, translated; the second value says whether it was
  /// an identity.
  (String, bool) _columnLine(String item) {
    final name = RegExp(r'^\S+').firstMatch(item)![0]!;
    var rest = item.substring(name.length).trim();
    final type = RegExp(
      r'^(\w+)(\s*\([^)]*\))?(\s+(?:UNSIGNED|ZEROFILL|PRECISION))*',
      caseSensitive: false,
    ).firstMatch(rest)!;
    final declared =
        '${type.group(1)}${type.group(2)?.replaceAll(' ', '') ?? ''}';
    rest = rest.substring(type.end);
    final identity = RegExp(
      r'\bAUTO_INCREMENT\b',
      caseSensitive: false,
    ).hasMatch(rest);
    // A binary collation is how the canonical DDL asks for case-sensitive
    // identity and code-unit order; PostgreSQL's equivalent is the C
    // collation. Any other collation is MariaDB's own and is dropped.
    rest = rest.replaceAll(
      RegExp(r'\bCOLLATE\s+\w*_bin\b', caseSensitive: false),
      '\u0000BINARY_COLLATION\u0000',
    );
    rest = rest
        .replaceAll(RegExp(r'\bAUTO_INCREMENT\b', caseSensitive: false), '')
        .replaceAll(
          RegExp(
            r"\bCOMMENT\s+'(?:[^']|'')*'|\bCHARACTER\s+SET\s+\w+|\bCHARSET\s+\w+|\bCOLLATE\s+\w+|\bON\s+UPDATE\s+CURRENT_TIMESTAMP(\(\d*\))?",
            caseSensitive: false,
          ),
          '',
        );
    final translated = columnType(declared);
    if (translated == 'SMALLINT') {
      rest = rest
          .replaceAll(
            RegExp(r'\bDEFAULT\s+TRUE\b', caseSensitive: false),
            'DEFAULT 1',
          )
          .replaceAll(
            RegExp(r'\bDEFAULT\s+FALSE\b', caseSensitive: false),
            'DEFAULT 0',
          );
    }
    rest = rest
        .replaceAll('\u0000BINARY_COLLATION\u0000', 'COLLATE "C"')
        .replaceAll(RegExp(r'\s+'), ' ')
        .trim();
    // An ENUM's value list is a constraint as well as a type; PostgreSQL keeps
    // the constraint as a CHECK on the VARCHAR it stores the value in.
    final enumValues = baseTypeName(declared) == 'ENUM'
        ? typeArguments(declared)
        : const <String>[];
    final line = [
      name,
      translated,
      if (identity) 'GENERATED BY DEFAULT AS IDENTITY',
      if (rest.isNotEmpty) rest,
      if (enumValues.isNotEmpty) 'CHECK ($name IN (${enumValues.join(', ')}))',
    ].join(' ');
    return (line, identity);
  }

  static String _indexName(String table, String name) {
    final bare = table.split('.').last;
    return name.toLowerCase().contains(bare.toLowerCase())
        ? name
        : '${bare}_$name';
  }

  static List<String> _keyColumns(String list) => [
    for (final c in list.split(','))
      // A MariaDB prefix length — `name(64)` — has no PostgreSQL form; the
      // whole column is indexed.
      c
          .trim()
          .replaceFirst(RegExp(r'\(\d+\)$'), '')
          .split(RegExp(r'\s+'))
          .first,
  ];

  static String _unbacktick(String sql) => sql.replaceAll('`', '');

  /// The index of the parenthesis closing the one at [open], skipping quoted
  /// text.
  static int _matching(String sql, int open) {
    var depth = 0;
    String? quote;
    for (var i = open; i < sql.length; i++) {
      final c = sql[i];
      if (quote != null) {
        if (c == quote) quote = null;
        continue;
      }
      if (c == "'" || c == '"') {
        quote = c;
      } else if (c == '(') {
        depth++;
      } else if (c == ')') {
        depth--;
        if (depth == 0) return i;
      }
    }
    return sql.length - 1;
  }

  /// [body] split at the commas outside parentheses and quotes.
  static List<String> _splitTopLevel(String body) {
    final items = <String>[];
    var depth = 0;
    String? quote;
    var start = 0;
    for (var i = 0; i < body.length; i++) {
      final c = body[i];
      if (quote != null) {
        if (c == quote) quote = null;
        continue;
      }
      if (c == "'" || c == '"') {
        quote = c;
      } else if (c == '(') {
        depth++;
      } else if (c == ')') {
        depth--;
      } else if (c == ',' && depth == 0) {
        items.add(body.substring(start, i).trim());
        start = i + 1;
      }
    }
    final last = body.substring(start).trim();
    if (last.isNotEmpty) items.add(last);
    return [
      for (final item in items)
        if (item.isNotEmpty) item,
    ];
  }
}
