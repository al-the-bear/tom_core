/// Executable example for the endpoints module of `tom_core_server`.
///
/// The full pipeline ([TomEndpointRouting] / [TomEndpointHandler]) reflects over
/// annotated service classes and serves live HTTP requests, so it needs a
/// running server — it is described in `doc/endpoints.md` rather than run here.
/// Everything below needs neither a server nor a socket: the endpoint-defining
/// annotations, the default error handler's `Response`, both form decoders
/// working on requests built in-process, and the file-slot registry.
///
/// The file-slot step does need generated reflection, because a slot is derived
/// from an entity's annotations. It comes from `example/example_reflection.dart`
/// — the example suite's single reflection root, regenerated by
/// `./reflection_generation.sh`.
///
/// Run with `dart run example/endpoints/endpoints_example.dart`. Every step
/// checks its own result and the run fails when one does not hold, so a green
/// run is a verification and not just a transcript.
/// The same behaviour is covered by `test/endpoints_test.dart`,
/// `test/endpoints_transport_test.dart` and, for the file slot,
/// `test/file_endpoint_test.dart`.
library;

import 'dart:convert';

import 'package:shelf/shelf.dart';
import 'package:tom_core_server/tom_core_server.dart';

import '../_support/check.dart';
import '../example_reflection.reflection.dart';
import 'endpoints_entities.dart';

/// A repository registered for its annotations only.
///
/// [TomFileSlots.register] reads the entity's table and file columns through the
/// reflector and never calls a repository method, so a type that could not serve
/// a request is still a perfectly good argument. It has to be a stand-in rather
/// than a real `TomSqlDatasourceRepository`, because constructing one of those
/// resolves its data source — and this example has no database.
class AnnotationsOnlyRepository
    implements TomFileRepository<ExampleDocumentRecord, int> {
  @override
  Never noSuchMethod(Invocation invocation) => throw UnimplementedError(
    'This repository is registered for its annotations only.',
  );
}

Future<void> run() async {
  // 1. An inline endpoint declaration. Every field has a default, so a bare
  //    @TomEndpoint() is a JSON GET at "/".
  const endpoint = TomEndpoint(
    uri: '/greet',
    methods: [TomHttpMethod.post, TomHttpMethod.put],
  );
  print('1. endpoint: ${endpoint.uri} ${endpoint.methods}');
  print('   consumes=${endpoint.consumes} produces=${endpoint.produces}');
  check(endpoint.uri == '/greet', 'an endpoint serves the route it names');
  check(endpoint.methods.length == 2, 'one endpoint answers several methods');
  check(
    endpoint.consumes == TomMimeType.json,
    'an endpoint that names no media type is JSON',
  );
  // convertToTomEndpoint returns the endpoint itself.
  check(
    identical(endpoint.convertToTomEndpoint(), endpoint),
    'a plain endpoint converts to itself',
  );

  // 2. A registry-bound endpoint only carries implementation-side overrides;
  //    the route comes from tomRemoteApis[apiId][endpointId].
  const apiEndpoint = TomApiEndpointImplementation(
    apiId: 'orders',
    endpointId: 'create',
    logRequests: true,
  );
  print(
    '2. api endpoint: ${apiEndpoint.apiId}.${apiEndpoint.endpointId} '
    'logRequests=${apiEndpoint.logRequests}',
  );
  check(apiEndpoint.apiId == 'orders', 'a bound endpoint names its api');

  // 3. Class-level markers: a service to scan, an API implementation, and a
  //    component reference pointing at the implementing bean.
  const service = tomService;
  const apiImpl = TomApiImplementation(apiId: 'orders');
  const ref = TomComponentReference(componentName: 'orderService');
  print(
    '3. service=$service apiImpl=${apiImpl.apiId} '
    'ref=${ref.componentName} logDefault=${apiImpl.logRequestsDefault}',
  );
  check(
    apiImpl.logRequestsDefault == true,
    'an api implementation logs its requests unless told otherwise',
  );
  check(
    ref.componentName == 'orderService',
    'a component reference names the bean that implements it',
  );

  // 4. A transactional, read-only endpoint directive.
  const tx = TomTransactional(isReadOnly: true);
  print('4. transactional=${tx.isTransactional} readOnly=${tx.isReadOnly}');
  check(tx.isTransactional == true, 'the directive opens a transaction');
  check(tx.isReadOnly == true, 'a read-only directive forbids writes');

  // 5. The default error handler hides the error behind an opaque 500.
  const handler = TomDefaultErrorHandler();
  final response = handler.handleInvocationError(
    StateError('boom'),
    StackTrace.current,
    Request('POST', Uri.parse('http://localhost/greet')),
  );
  print('5. default error handler => HTTP ${response.statusCode}');
  check(
    response.statusCode == 500,
    'an unhandled error reaches the caller as an opaque server error',
  );

  // 6. A form endpoint. `formFields` is an allow-list: left empty, every text
  //    part folds into the request DTO; named, only those do.
  const formEndpoint = TomEndpoint(
    uri: '/documents',
    methods: [TomHttpMethod.post],
    consumes: TomMimeType.multipartFormData,
    formFields: ['title', 'tags'],
  );
  print(
    '6. form endpoint: ${formEndpoint.uri} '
    'consumes=${formEndpoint.consumes} fields=${formEndpoint.formFields}',
  );
  // Both HTML form shapes answer the same question; only the reading differs.
  check(tomConsumesForm(formEndpoint.consumes), 'multipart is a form shape');
  check(tomConsumesForm(TomMimeType.urlEncoded), 'so is url-encoded');
  check(!tomConsumesForm(TomMimeType.json), 'a JSON endpoint is not a form');
  check(
    tomConsumesMultipartForm(formEndpoint.consumes),
    'only multipart can carry a file part',
  );
  check(
    !tomConsumesMultipartForm(TomMimeType.urlEncoded),
    'a form without a file input is read the other way',
  );

  // 7. Decoding one. `readForm` takes a shelf Request and needs no server, so
  //    the body below is the wire format a browser actually sends — a boundary
  //    delimiter, one part per field, and a closing delimiter with a trailing
  //    `--`. Text fields fold into the request DTO; file parts bind as typed
  //    parameters, because a file cannot travel through a JSON map into a DTO.
  //
  //    Which part is which is the *envelope's* distinction and not a guess from
  //    the media type: `attachment` is a file part because its
  //    content-disposition carries a `filename`, and `tags` is a text part
  //    because its does not.
  const boundary = 'tomexampleboundary';
  const multipartBody =
      '--$boundary\r\n'
      'content-disposition: form-data; name="title"\r\n'
      '\r\n'
      'Quarterly report\r\n'
      '--$boundary\r\n'
      'content-disposition: form-data; name="tags"\r\n'
      '\r\n'
      'q3,final\r\n'
      '--$boundary\r\n'
      'content-disposition: form-data; name="attachment"; '
      'filename="q3.txt"\r\n'
      'content-type: text/plain\r\n'
      '\r\n'
      'the numbers\r\n'
      '--$boundary--\r\n';
  final form = await TomMultipartForm.readForm(
    Request(
      'POST',
      Uri.parse('http://localhost/documents'),
      headers: {'content-type': 'multipart/form-data; boundary=$boundary'},
      body: multipartBody,
    ),
  );
  final attachment = form!.file('attachment')!;
  print(
    '7. decoded multipart: fields=${form.fields.keys.toList()} '
    'file=${attachment.fileName} (${attachment.byteCount} bytes, '
    '${attachment.mediaType})',
  );
  print('   attachment content: "${utf8.decode(attachment.bytes)}"');
  check(form.fields.length == 2, 'both text parts fold in');
  check(form.fields['title'] == 'Quarterly report', 'a text part is its value');
  check(utf8.decode(attachment.bytes) == 'the numbers', 'the bytes survive');
  check(attachment.fileName == 'q3.txt', 'the file part carries its name');
  check(form.file('missing') == null, 'an absent file part is null, not empty');
  //    A request that is not a form at all answers `null` rather than throwing:
  //    "is this a form?" is what the pipeline asks of *every* request, and a
  //    JSON endpoint asking it must not have to catch anything.
  final notAForm = await TomMultipartForm.readForm(
    Request(
      'POST',
      Uri.parse('http://localhost/documents'),
      headers: {'content-type': TomMimeType.json.toHeaderValue()},
      body: '{"title":"Quarterly report"}',
    ),
  );
  print('   a JSON request decodes to: $notAForm');
  check(notAForm == null, 'a non-form request is not a decode failure');

  // 8. The other shape an HTML form takes — the one a form without a file input
  //    sends by default. It carries no parts and so never any files, which is
  //    why it decodes to the same type: everything downstream of the decode is
  //    identical, and only the reading differs.
  final urlEncoded = await TomMultipartForm.readUrlEncodedForm(
    Request(
      'POST',
      Uri.parse('http://localhost/documents'),
      headers: {'content-type': TomMimeType.urlEncoded.toHeaderValue()},
      body: 'title=Quarterly%20report&tags=q3%2Cfinal',
    ),
  );
  print(
    '8. decoded url-encoded: ${urlEncoded.fields} '
    'files=${urlEncoded.files.length}',
  );
  //    Percent-escapes are decoded, so the DTO sees the text the user typed.
  check(urlEncoded.fields['tags'] == 'q3,final', 'escapes are decoded');
  check(urlEncoded.files.isEmpty, 'a url-encoded body can carry no file');

  // 9. A redirect is a directive, not a hand-built response: the handler states
  //    the status and the URL, and the pipeline builds the Response.
  final redirect = TomRedirect.seeOther('/documents/42');
  final redirectResponse = redirect.toResponse();
  print(
    '9. redirect => HTTP ${redirectResponse.statusCode} '
    '-> ${redirectResponse.headers[TomHeader.location.toLowerCase()]}',
  );
  check(
    redirectResponse.statusCode == 303,
    'a see-other sends the caller on with a fresh GET',
  );
  check(
    TomRedirect.permanent('/x').status == 308,
    'a permanent redirect keeps the original method',
  );

  // 10. A socket is a kind of endpoint, not a second server: it implements the
  //     same TomEndpointBase the scan already keys on, and converts to a GET.
  const socketEndpoint = TomWebSocketEndpoint(uri: '/ws/ticker');
  final converted = socketEndpoint.convertToTomEndpoint();
  print(
    '10. socket endpoint: ${socketEndpoint.uri} '
    'routes as ${converted.methods}',
  );
  // Assigning it to the base type is the whole point: `tag is TomEndpointBase`
  // is what the pipeline's scan asks of every annotation it finds.
  const TomEndpointBase asBase = socketEndpoint;
  check(
    identical(asBase, socketEndpoint),
    'a socket is one of the endpoints the scan already finds',
  );
  check(
    converted.methods.single == TomHttpMethod.get,
    'a socket routes as one ordinary GET',
  );

  // 11. A file slot. The route is fixed and the address is derived: a slot is
  //     `<table>/<id>/<column>`, and both names come from annotations the
  //     entity already carries, so no mapping table exists here to go stale.
  print('11. file route: ${TomFileEndpoint.routeUri}');
  check(
    TomFileEndpoint.routeUri ==
        '${TomFileEndpoint.basePath}/{entity}/{id}/{column}',
    'a file route carries the three slot segments',
  );

  //     Exposure is default-closed, and that is observable *before* anything is
  //     registered. Reflection can see every file column of every entity and
  //     publishes none of them.
  check(
    TomFileSlots.slots.isEmpty,
    'no slot is reachable before a repository is registered',
  );

  //     Registration is per *repository*, not per column: the repository already
  //     carries the entity type and the key type, and the entity's annotations
  //     carry the table name, the column names and the blob store. Anything else
  //     would be a restatement, and a restatement is what drifts.
  TomFileSlots.register(AnnotationsOnlyRepository());
  for (final slot in TomFileSlots.slots) {
    // A slot is named `<table>/<column>`; the route it answers on puts the row
    // id between them, which is the whole of the addressing scheme.
    final [table, column] = slot.split('/');
    print(
      '    slot "$slot" serves ${TomFileEndpoint.basePath}'
      '/$table/{id}/$column',
    );
  }

  //     [ExampleDocumentRecord] declares *two* `@TomFileReference` columns and
  //     marks one of them `exposed: true`. Exactly one slot exists, so the
  //     default is visible in the positive case too: adding a file column to an
  //     entity does not put it on the network.
  check(
    TomFileSlots.slots.length == 1 &&
        TomFileSlots.slots.single == 'example_document/attachment',
    'only the exposed column becomes a slot',
  );
  check(
    TomFileSlots.resolve('example_document', 'internal_draft') == null,
    'a closed column of a registered entity still resolves to nothing',
  );

  //     Which is the answer step 7's form part gets when it aims at the closed
  //     column. `storeIn` is the join between the two upload shapes — a
  //     multipart part reaches the store through the *same* slot the raw-body
  //     endpoint uses — so it meets the same closed door and reports it the same
  //     way. Over HTTP that key is a 404: a closed column is answered exactly as
  //     a non-existent one, rather than telling a caller which columns exist but
  //     are not theirs.
  try {
    await attachment.storeIn('example_document', 'internal_draft', '42');
    throw StateError('storing into a closed column must not succeed');
  } on TomFileSlotException catch (error) {
    print('    storeIn to the closed column => ${error.key}');
    if (error.key != 'file_endpoint.unknown_slot') rethrow;
  }

  print('\nEndpoints example completed.');
}

Future<void> main() async {
  // Reflection first: a file slot is derived from an entity's annotations, so
  // `TomFileSlots.register` in step 11 throws "Reflection has not been
  // initialized" without this. It is what any deployment does at start-up.
  initializeReflection();
  await run();
}
