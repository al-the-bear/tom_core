// ignore_for_file: avoid_print
// Generates tom_icons_generated.dart from Flutter SDK icon source files.
// Run with: dart run tool/generate_icons.dart
import 'dart:io';

void main() async {
  final flutterSdk = _findFlutterSdk();
  if (flutterSdk == null) {
    print('Error: Could not find Flutter SDK');
    exit(1);
  }

  print('Flutter SDK: $flutterSdk');

  final materialIconsFile = File(
    '$flutterSdk/packages/flutter/lib/src/material/icons.dart',
  );
  final cupertinoIconsFile = File(
    '$flutterSdk/packages/flutter/lib/src/cupertino/icons.dart',
  );

  if (!materialIconsFile.existsSync()) {
    print('Error: Material icons file not found');
    exit(1);
  }
  if (!cupertinoIconsFile.existsSync()) {
    print('Error: Cupertino icons file not found');
    exit(1);
  }

  // Extract icon names
  final materialIcons = _extractIconNames(
    materialIconsFile.readAsStringSync(),
  );
  final cupertinoIcons = _extractIconNames(
    cupertinoIconsFile.readAsStringSync(),
  );

  print('Found ${materialIcons.length} Material icons');
  print('Found ${cupertinoIcons.length} Cupertino icons');

  // Generate the output file
  final output = _generateOutput(materialIcons, cupertinoIcons);

  // Write to lib/src/resource_auth/tom_icons_generated.dart
  final outputFile = File('lib/src/resource_auth/tom_icons_generated.dart');
  outputFile.writeAsStringSync(output);

  print('Generated ${outputFile.path}');
  print('Total icons: ${materialIcons.length + cupertinoIcons.length}');
}

String? _findFlutterSdk() {
  // Try 'which flutter' approach
  final result = Process.runSync('which', ['flutter']);
  if (result.exitCode == 0) {
    final flutterBin = (result.stdout as String).trim();
    // flutter binary is at <sdk>/bin/flutter
    final sdkDir = File(flutterBin).parent.parent;
    if (sdkDir.existsSync()) {
      return sdkDir.path;
    }
  }

  // Try FLUTTER_ROOT environment variable
  final flutterRoot = Platform.environment['FLUTTER_ROOT'];
  if (flutterRoot != null && Directory(flutterRoot).existsSync()) {
    return flutterRoot;
  }

  return null;
}

List<String> _extractIconNames(String source) {
  final regex = RegExp(r'static const IconData (\w+)\s*=');
  final matches = regex.allMatches(source);
  return matches.map((m) => m.group(1)!).toList();
}

String _capitalize(String s) {
  if (s.isEmpty) return s;
  // Handle snake_case: ten_k -> TenK
  final parts = s.split('_');
  return parts.map((p) => p.isEmpty ? '' : p[0].toUpperCase() + p.substring(1)).join();
}

String _generateOutput(List<String> materialIcons, List<String> cupertinoIcons) {
  final buffer = StringBuffer();

  buffer.writeln('// GENERATED FILE - DO NOT EDIT');
  buffer.writeln('// Generated by: dart run tool/generate_icons.dart');
  buffer.writeln('// Generated on: ${DateTime.now().toIso8601String()}');
  buffer.writeln('//');
  buffer.writeln('// Material icons: ${materialIcons.length}');
  buffer.writeln('// Cupertino icons: ${cupertinoIcons.length}');
  buffer.writeln('// Total: ${materialIcons.length + cupertinoIcons.length}');
  buffer.writeln();
  buffer.writeln("import 'package:flutter/cupertino.dart';");
  buffer.writeln("import 'package:flutter/material.dart';");
  buffer.writeln();
  buffer.writeln('/// Generated icon mappings for all Flutter icons.');
  buffer.writeln('///');
  buffer.writeln('/// Material icons are prefixed with `m` (e.g., `mAdd`, `mSave`).');
  buffer.writeln('/// Cupertino icons are prefixed with `c` (e.g., `cShare`, `cBook`).');
  buffer.writeln('///');
  buffer.writeln('/// The original snake_case names are converted to PascalCase after the prefix.');
  buffer.writeln('/// Example: `arrow_back` -> `mArrowBack`, `left_chevron` -> `cLeftChevron`');
  buffer.writeln('class GeneratedIcons {');
  buffer.writeln('  GeneratedIcons._();');
  buffer.writeln();
  buffer.writeln('  /// All Material icons, keyed by `m<PascalCaseName>`.');
  buffer.writeln('  static const Map<String, IconData> materialIcons = {');

  for (final icon in materialIcons) {
    final key = 'm${_capitalize(icon)}';
    buffer.writeln("    '$key': Icons.$icon,");
  }

  buffer.writeln('  };');
  buffer.writeln();
  buffer.writeln('  /// All Cupertino icons, keyed by `c<PascalCaseName>`.');
  buffer.writeln('  static const Map<String, IconData> cupertinoIcons = {');

  for (final icon in cupertinoIcons) {
    final key = 'c${_capitalize(icon)}';
    buffer.writeln("    '$key': CupertinoIcons.$icon,");
  }

  buffer.writeln('  };');
  buffer.writeln();
  buffer.writeln('  /// Resolves an icon by name.');
  buffer.writeln('  ///');
  buffer.writeln('  /// Names starting with `m` look up Material icons.');
  buffer.writeln('  /// Names starting with `c` look up Cupertino icons.');
  buffer.writeln('  static IconData? resolve(String name) {');
  buffer.writeln('    return materialIcons[name] ?? cupertinoIcons[name];');
  buffer.writeln('  }');
  buffer.writeln();
  buffer.writeln('  /// Whether an icon with [name] exists.');
  buffer.writeln('  static bool exists(String name) {');
  buffer.writeln('    return materialIcons.containsKey(name) || cupertinoIcons.containsKey(name);');
  buffer.writeln('  }');
  buffer.writeln('}');

  return buffer.toString();
}
