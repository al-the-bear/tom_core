// TomFormFileUpload — compact "Choose file…" affordance
// ===========================================================================

@tomReflector
class TomFormFileUpload extends TomFormFileField
    with TomGenericFieldDecorationMixin<FileRef?> {
  TomFormFileUpload(
    super.tomId,
    super.initialValue, {
    super.picker,
    super.pickKind,
    super.transferClient,
    super.storageSlot,
    super.autoUpload,
    super.onDownload,
    super.labelTextOverride,
    super.descriptionTextOverride,
    super.allowedExtensions,
    super.maxSizeBytes,
    super.form,
    super.validators,
    super.autoValidate,
    super.tomGroup,
    super.authorizer,
    super.uiStateController,
    super.actionIcon,
    super.actionIconTooltip,
    super.onActionIconPressed,
  });

  @override
  TomFieldStyle resolveStyle(BuildContext context) {
    final form = TomFormStyleScope.of(context);
    final width = TomFormStyleScope.widthOf(context);
    return form.resolveFieldStyle(form.dropdownStyle, width);
  }

  @override
  Widget get widget =>
      TomFieldWidgetAdapter(field: this, child: _FileUploadWidget(field: this));
}

class _FileUploadWidget extends StatefulWidget {
  final TomFormFileUpload field;
  const _FileUploadWidget({required this.field});

  @override
  State<_FileUploadWidget> createState() => _FileUploadWidgetState();
}

class _FileUploadWidgetState extends State<_FileUploadWidget>
    with TomFileFieldStateMixin<_FileUploadWidget> {
  @override
  TomFormFileField get field => widget.field;

  @override
  Future<void> showFileRejected(String errorKey) async {
    TomMessenger.showSnackBarIfPresent(
      context,
      SnackBar(content: Text(errorKey)),
    );
  }

  @override
  Widget build(BuildContext context) {
    final f = widget.field;
    final style = f.resolveStyle(context);
    final v = f.get();

    final column = Column(
      mainAxisSize: MainAxisSize.min,
      crossAxisAlignment: CrossAxisAlignment.stretch,
      children: [
        Row(
          children: [
            OutlinedButton.icon(
              onPressed: f.isEditable && f.canPick ? pick : null,
              icon: const Icon(Icons.upload_file),
              label: const Text('Choose file…'),
            ),
            const SizedBox(width: 8),
            Expanded(
              child: Text(
                v == null
                    ? '— no file selected'
                    : '${v.name} (${humanSize(v.sizeBytes)})',
                style: style.inputStyle,
                overflow: TextOverflow.ellipsis,
              ),
            ),
            if (canDownload)
              IconButton(
                tooltip: 'Download',
                icon: const Icon(Icons.download),
                onPressed: download,
              ),
            if (v != null && f.isEditable)
              IconButton(
                tooltip: 'Clear',
                icon: const Icon(Icons.clear),
                onPressed: clear,
              ),
          ],
        ),
        if (transferController != null)
          TomFileTransferIndicator(
            controller: transferController!,
            onCancel: cancelTransfer,
            onRetry: retryTransfer,
          ),
      ],
    );

    return f.decorateField(context, column);
  }
}

