class _FileUploadWidget extends StatefulWidget {
  final TomFormFileUpload field;
  const _FileUploadWidget({required this.field});

  @override
  State<_FileUploadWidget> createState() => _FileUploadWidgetState();
}

class _FileUploadWidgetState extends State<_FileUploadWidget>
    with TomFileFieldStateMixin<_FileUploadWidget> {
  @override
  TomFormFileField get field => widget.field;

  @override
  Future<void> showFileRejected(String errorKey) async {
    TomMessenger.showSnackBarIfPresent(
      context,
      SnackBar(content: Text(rejectionMessage(errorKey))),
    );
  }

  @override
  Widget build(BuildContext context) {
    final f = widget.field;
    final style = f.resolveStyle(context);
    final v = f.get();

    final column = Column(
      mainAxisSize: MainAxisSize.min,
      crossAxisAlignment: CrossAxisAlignment.stretch,
      children: [
        Row(
          children: [
            OutlinedButton.icon(
              onPressed: f.isEditable && f.canPick ? pick : null,
              icon: const Icon(Icons.upload_file),
              label: Text(TomFileLabels.choose(f.basePath)),
            ),
            const SizedBox(width: 8),
            Expanded(
              child: Text(
                v == null
                    ? TomFileLabels.none(f.basePath)
                    : selectedCaption(v),
                style: style.inputStyle,
                overflow: TextOverflow.ellipsis,
              ),
            ),
            if (canDownload)
              IconButton(
                tooltip: TomFileLabels.download(f.basePath),
                icon: const Icon(Icons.download),
                onPressed: download,
              ),
            if (v != null && f.isEditable)
              IconButton(
                tooltip: TomFileLabels.clear(f.basePath),
                icon: const Icon(Icons.clear),
                onPressed: clear,
              ),
          ],
        ),
        if (transferController != null)
          TomFileTransferIndicator(
            controller: transferController!,
            basePath: f.basePath,
            onCancel: cancelTransfer,
            onRetry: retryTransfer,
          ),
      ],
    );

    return f.decorateField(context, column);
  }
}

