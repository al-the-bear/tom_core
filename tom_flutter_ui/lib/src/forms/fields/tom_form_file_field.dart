/// The pick → validate → store → upload sequence and the transfer state that
/// goes with it, shared by every file-field widget in both families.
///
/// A mixin rather than a base class because the Material and Cupertino widgets
/// have nothing else in common: they share this behaviour and no chrome at all.
mixin TomFileFieldStateMixin<TWidget extends StatefulWidget> on State<TWidget> {
  late final TomFunctionObserver<TomObservable> _observer;

  /// The controller for this field's slot, or `null` when the field is
  /// picker-only.
  TomFileTransferController? transferController;

  TomFormFileField get field;

  @override
  void initState() {
    super.initState();
    _observer = field >> (_) {
      if (!mounted) return;
      setState(() {});
      onFieldValueChanged();
    };
    field.validationListenable.addListener(_onValidationChanged);
    transferController = field.createTransferController();
    if (transferController != null) {
      transferController!.addListener(_onTransferChanged);
      // A field whose value already names a stored file was restored from a
      // saved form; describing the slot costs one HEAD and is what lets the
      // widget show a download affordance for it.
      if (field.get()?.isStored ?? false) {
        unawaited(_describeQuietly());
      }
    }
  }

  /// Called after the field's value changed and the rebuild was scheduled.
  ///
  /// A hook rather than a second observer because the work it exists for —
  /// fetching a preview — is asynchronous and so cannot happen inside the
  /// `setState` callback. Empty by default; only the thumbnail overrides it.
  void onFieldValueChanged() {}

  Future<void> _describeQuietly() async {
    try {
      await transferController?.describe();
    } on Object {
      // A describe is an optimisation, not the user's request: a slot that
      // cannot be described still renders from the value the field holds.
    }
  }

  void _onValidationChanged() {
    if (mounted) setState(() {});
  }

  void _onTransferChanged() {
    if (mounted) setState(() {});
  }

  @override
  void dispose() {
    field.validationListenable.removeListener(_onValidationChanged);
    field.removeObserver(_observer);
    transferController?.removeListener(_onTransferChanged);
    transferController?.dispose();
    super.dispose();
  }

  /// Reports a rejected file to the user.
  ///
  /// Overridden per family — Material has a `ScaffoldMessenger`, Cupertino has
  /// a dialog — which is the only reason `pick` is not fully generic. The
  /// *wording* is not per-family: resolve [errorKey] through
  /// [rejectionMessage] rather than showing the key.
  Future<void> showFileRejected(String errorKey);

  /// The sentence to show for a file [TomFormFileField.checkFile] refused.
  ///
  /// Here rather than at each override because every family owes the user the
  /// same explanation for the same refusal, and because the key itself
  /// ("error.fileTooLarge") is a thing to look up, not a thing to read.
  String rejectionMessage(String errorKey) =>
      TomFileLabels.rejection(field.basePath, errorKey);

  /// Opens the picker, validates the result, stores it and (when configured)
  /// uploads it.
  Future<void> pick() async {
    final picked = await field.runPicker(context);
    if (picked == null) return;
    final err = field.checkFile(picked);
    if (err != null) {
      if (!mounted) return;
      await showFileRejected(err);
      return;
    }
    field.setValue(picked);
    if (field.autoUpload) await upload(picked);
  }

  /// Uploads [ref], replacing the field's value with the stored reference.
  ///
  /// The replacement is what makes the upload visible to the rest of the form:
  /// a value carrying a storage key is a value the form can save.
  Future<void> upload(FileRef ref) async {
    final controller = transferController;
    if (controller == null || !ref.hasLocalContent) return;
    final stored = await controller.upload(ref);
    if (stored == null || !mounted) return;
    field.setValue(ref.copyWith(storageKey: stored.key));
  }

  /// Retries the last failed or cancelled transfer.
  Future<void> retryTransfer() async => transferController?.retry();

  /// Cancels the transfer in flight.
  void cancelTransfer() => transferController?.cancel();

  /// Downloads the stored file and hands its bytes to the field's
  /// `onDownload` callback.
  Future<void> download() async {
    final controller = transferController;
    final ref = field.get();
    if (controller == null || ref == null) return;
    final bytes = await controller.download();
    if (bytes == null || !mounted) return;
    field.onDownload?.call(ref, bytes);
  }

  /// Clears the field, and the stored file with it when there is one.
  ///
  /// Deleting the stored file is the point: leaving an orphan blob behind
  /// every time a user changes their mind is how a store fills up.
  Future<void> clear() async {
    final ref = field.get();
    field.setValue(null);
    if (ref?.isStored ?? false) {
      try {
        await transferController?.remove();
      } on Object {
        // The field is already cleared; a failed cleanup must not undo that.
      }
    } else {
      transferController?.reset();
    }
  }

  /// Whether the download affordance should be offered.
  bool get canDownload =>
      field.onDownload != null && (field.get()?.isStored ?? false);

  String humanSize(int bytes) => tomHumanFileSize(bytes);

  /// The caption naming [ref] and its size, resolved from resources.
  ///
  /// Shared because both concretes show the same thing for a chosen file; they
  /// differ only in what they say when there is *no* file, which is a different
  /// sentence in each ("— no file selected" vs. an invitation to tap).
  String selectedCaption(FileRef ref) => TomFileLabels.selected(
    field.basePath,
    ref.name,
    humanSize(ref.sizeBytes),
  );
}

/// A human-readable rendering of a byte count.
///
/// Free function because three widgets and an example need it and none of them
/// owns it.
String tomHumanFileSize(int bytes) {
  if (bytes < 1024) return '$bytes B';
  if (bytes < 1024 * 1024) return '${(bytes / 1024).toStringAsFixed(1)} KB';
  return '${(bytes / (1024 * 1024)).toStringAsFixed(2)} MB';
}

// ===========================================================================
// Thumbnails — deciding what can be painted, and getting the bytes to paint
// ===========================================================================

/// The extensions Flutter's own codecs can decode.
///
/// Deliberately not "every image format": SVG and friends need a package, and
/// a field that promised to paint one would show a broken box instead of the
/// icon the fallback exists for.
const Set<String> _renderableImageExtensions = {
  'png',
  'jpg',
  'jpeg',
  'gif',
  'webp',
  'bmp',
  'wbmp',
};

/// Whether [ref] names a file [TomFormFileThumbnail] can paint inline.
///
/// Three sources, consulted in order of how much they actually know:
///
///  1. the reported media type, when the picker or the server gave one;
///  2. the file's extension, when the name carries one;
///  3. [pickKind] — the last thing left to go on.
///
/// The order matters more than the sources do. `pickKind` states what the
/// field *asked for*, not what the value *is*, so it must never overrule a
/// media type or an extension: an `image` field holding a PDF would otherwise
/// hand PDF bytes to an image codec.
///
/// A free function for the same reason as [tomHumanFileSize] — both widget
/// families need it and neither owns it.
bool tomFileIsRenderableImage(FileRef ref, TomFilePickKind pickKind) {
  final mediaType = ref.mimeType;
  if (mediaType != null && mediaType.isNotEmpty) {
    return mediaType.startsWith('image/') &&
        _renderableImageExtensions.contains(
          mediaType.substring('image/'.length).toLowerCase(),
        );
  }
  final extension = ref.extension;
  if (extension.isNotEmpty) {
    return _renderableImageExtensions.contains(extension);
  }
  return pickKind == TomFilePickKind.image;
}

/// The preview bytes behind a thumbnail, and the one fetch that gets them.
///
/// Layered on [TomFileFieldStateMixin] rather than folded into it: only the
/// thumbnail presentation needs a file's *content*, and the other two would
/// pay for a download they never paint.
mixin TomFileThumbnailStateMixin<TWidget extends StatefulWidget>
    on TomFileFieldStateMixin<TWidget> {
  Uint8List? _fetchedPreview;

  /// The storage key a fetch was already attempted for.
  ///
  /// Attempted, not succeeded — a slot that failed once must not be retried on
  /// every rebuild.
  String? _attemptedForKey;

  /// The bytes to paint, or `null` when there is nothing paintable yet.
  Uint8List? get previewBytes {
    final ref = field.get();
    if (ref == null || !tomFileIsRenderableImage(ref, field.pickKind)) {
      return null;
    }
    return ref.bytes ?? _fetchedPreview;
  }

  @override
  void initState() {
    super.initState();
    unawaited(ensurePreview());
  }

  @override
  void onFieldValueChanged() {
    super.onFieldValueChanged();
    final key = field.get()?.storageKey;
    if (key != _attemptedForKey) {
      // A different file — anything fetched for the old one is not this one's
      // content, and painting it would show the user the wrong picture.
      _fetchedPreview = null;
      _attemptedForKey = null;
    }
    unawaited(ensurePreview());
  }

  /// Reads the bytes of a stored, renderable file that carries none locally.
  ///
  /// Straight through the transfer *client*, not the controller: a preview is
  /// the widget's own read, and a controller download publishes `running` and
  /// `succeeded`, so the status row would announce "Downloading…" and
  /// "Downloaded." for something the user never asked for.
  Future<void> ensurePreview() async {
    final ref = field.get();
    final client = field.transferClient;
    final slot = field.storageSlot;
    if (ref == null || client == null || slot == null) return;
    final key = ref.storageKey;
    if (key == null || ref.hasLocalContent) return;
    if (!tomFileIsRenderableImage(ref, field.pickKind)) return;
    if (_attemptedForKey == key) return;
    _attemptedForKey = key;

    try {
      final builder = BytesBuilder(copy: false);
      await for (final chunk in client.download(slot)) {
        builder.add(chunk);
      }
      final bytes = builder.takeBytes();
      if (!mounted) return;
      setState(() => _fetchedPreview = bytes);
    } on Object {
      // A preview is an optimisation, not the user's request: a file that
      // cannot be fetched still renders as its file-kind icon. `_attemptedForKey`
      // stays set, so the failure costs one read rather than one per frame.
    }
  }

  /// The inline preview, or [fallback] when there is nothing to paint.
  ///
  /// [fallback] is also the codec's error branch: bytes that turn out not to
  /// be an image after all land in the same place as a file that never claimed
  /// to be one.
  Widget previewOrFallback({required double size, required Widget fallback}) {
    final bytes = previewBytes;
    if (bytes == null) return fallback;
    return Image.memory(
      bytes,
      width: size,
      height: size,
      fit: BoxFit.cover,
      semanticLabel: field.get()?.name,
      errorBuilder: (_, _, _) => fallback,
    );
  }
}

