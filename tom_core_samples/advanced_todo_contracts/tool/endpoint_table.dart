/// Renders the README's endpoint table from the registry itself.
///
/// The three `TomApi` objects in `lib/src/api_registry.dart` are the contract:
/// the servers bind their handlers to them, and they carry every fact a
/// reader looks for — route, method, access, request and response types. A
/// hand-written table of those facts would be a second enumeration of the
/// wire, the failure this package exists to prevent. So the table is rendered
/// from the objects, and `test/readme_endpoint_table_test.dart` fails whenever
/// the README's copy differs from what this renders.
///
/// ```sh
/// dart run tool/endpoint_table.dart           # print the table
/// dart run tool/endpoint_table.dart --write   # rewrite it in README.md
/// dart run tool/endpoint_table.dart --check   # exit 1 when README.md is stale
/// ```
///
/// No sample carries a `doc/` folder (see `tom_core_samples/README.md`), so the
/// generated table lives in the README between two markers rather than in a
/// `doc/api/` file.
library;

import 'dart:io';

import 'package:advanced_todo_contracts/advanced_todo_contracts.dart';
import 'package:tom_core_kernel/tom_core_kernel.dart';

/// The marker line that opens the generated block in `README.md`.
const endpointTableStart =
    '<!-- endpoint-table:start — generated by tool/endpoint_table.dart -->';

/// The marker line that closes it.
const endpointTableEnd = '<!-- endpoint-table:end -->';

/// The APIs the table covers, in reading order.
final List<TomApi> tabledApis = [authApi, adminApi, appApi];

/// The markdown table, one section per API, rendered from [tabledApis].
String renderEndpointTable() {
  final out = StringBuffer();
  for (final api in tabledApis) {
    final count = api.endpoints.length;
    final base = (api.uri ?? '').isEmpty
        ? 'served at the root'
        : 'under `${api.uri}`';
    out
      ..writeln('#### `${api.id}` — ${api.name} ($count, $base)')
      ..writeln()
      ..writeln('| Endpoint | Method | Path | Request | Response | Access |')
      ..writeln('| --- | --- | --- | --- | --- | --- |');
    for (final endpoint in api.endpoints.values) {
      out.writeln(
        '| `${endpoint.id}` '
        '| ${endpoint.method.name.toUpperCase()} '
        '| `${api.uri ?? ''}${endpoint.uri ?? ''}` '
        '| ${_request(endpoint)} '
        '| ${_code('${endpoint.responseType}')} '
        '| ${describeAccess(endpoint.access)} |',
      );
    }
    out.writeln();
  }
  return out.toString().trimRight();
}

/// The request body type(s), or `—` for a body-less endpoint.
String _request(TomApiEndpoint<dynamic, dynamic> endpoint) {
  final types = endpoint.requestTypes
      .map((t) => '$t')
      .where((t) => t != 'Object?' && t != 'dynamic')
      .toList();
  return types.isEmpty ? '—' : types.map(_code).join(', ');
}

String _code(String text) => '`$text`';

/// The access policy in a word or two.
String describeAccess(TomAccessControl? access) => switch (access) {
  TomPublicAccess() => 'public',
  TomAuthenticatedAccess() => 'authenticated',
  TomRoleAccess(:final roles) => 'role `${roles.join('`, `')}`',
  null => '**undeclared**',
  _ => access.runtimeType.toString(),
};

/// [readme] with the text between the markers replaced by [table]; throws
/// when either marker is missing.
String replaceEndpointTable(String readme, String table) {
  final start = readme.indexOf(endpointTableStart);
  final end = readme.indexOf(endpointTableEnd);
  if (start < 0 || end < start) {
    throw StateError(
      'README.md has no endpoint-table markers; add\n'
      '$endpointTableStart\n$endpointTableEnd\nwhere the table belongs.',
    );
  }
  return '${readme.substring(0, start + endpointTableStart.length)}\n\n'
      '$table\n\n${readme.substring(end)}';
}

void main(List<String> args) {
  final table = renderEndpointTable();
  if (args.isEmpty) {
    stdout.writeln(table);
    return;
  }
  final readmeFile = File('README.md');
  final readme = readmeFile.readAsStringSync();
  final current = replaceEndpointTable(readme, table);
  if (args.contains('--write')) {
    readmeFile.writeAsStringSync(current);
    stdout.writeln('README.md endpoint table written.');
  } else if (args.contains('--check')) {
    if (current != readme) {
      stderr.writeln(
        'README.md endpoint table is stale — run '
        'dart run tool/endpoint_table.dart --write',
      );
      exitCode = 1;
    }
  }
}
